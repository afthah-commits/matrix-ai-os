/// The final response generated by Matrix AI OS RAG Orchestrator,
/// including transparent privacy and resource telemetry badges.
@immutable
class RagResponse {
  final String text;
  final int tokensMasked;
  final int localMemoriesUsed;
  final int webResultsUsed;
  final UserIntent intent;
  final bool isOfflineEngine;
  final String providerUsed;

  const RagResponse({
    required this.text,
    required this.tokensMasked,
    required this.localMemoriesUsed,
    required this.webResultsUsed,
    required this.intent,
    required this.isOfflineEngine,
    required this.providerUsed,
  });

  @override
  String toString() =>
      'RagResponse(tokensMasked: $tokensMasked, memories: $localMemoriesUsed, web: $webResultsUsed, offline: $isOfflineEngine)';
}

/// Orchestrates Hybrid RAG:
/// 1. Intent routing
/// 2. Local Knowledge Graph & encrypted memory retrieval
/// 3. Zero-leakage on-device PII masking
/// 4. Live web tool retrieval (DuckDuckGo Instant/HTML Lite)
/// 5. BYOK Cloud LLM invocation (Gemini / OpenAI) or Local Deterministic Engine
/// 6. Local on-device PII restoration
class HybridRagOrchestrator {
  final KnowledgeGraphService _knowledgeGraphService;
  final PiiMaskingService _piiMaskingService;
  final LiveWebSearchTool _webSearchTool;
  final IntentRouterService _intentRouter;
  final ByokKeyManager _byokManager;
  final http.Client _client;

  HybridRagOrchestrator({
    required KnowledgeGraphService knowledgeGraphService,
    required PiiMaskingService piiMaskingService,
    required LiveWebSearchTool webSearchTool,
    required IntentRouterService intentRouter,
    required ByokKeyManager byokManager,
    http.Client? client,
  })  : _knowledgeGraphService = knowledgeGraphService,
        _piiMaskingService = piiMaskingService,
        _webSearchTool = webSearchTool,
        _intentRouter = intentRouter,
        _byokManager = byokManager,
        _client = client ?? http.Client();

  /// Primary conversational query entry point.
  Future<RagResponse> processQuery(String userPrompt) async {
    final cleanPrompt = userPrompt.trim();
    if (cleanPrompt.isEmpty) {
      return const RagResponse(
        text: 'How can I assist you today?',
        tokensMasked: 0,
        localMemoriesUsed: 0,
        webResultsUsed: 0,
        intent: UserIntent.personalMemory,
        isOfflineEngine: true,
        providerUsed: 'Local Matrix Core',
      );
    }

    // 1. Intent Routing
    final intent = _intentRouter.classify(cleanPrompt);

    // 2. Fetch context
    KnowledgeQueryResult? personalResult;
    WebSearchResult? webResult;

    if (intent == UserIntent.personalMemory || intent == UserIntent.hybrid) {
      personalResult = await _knowledgeGraphService.queryRelatedMemories(cleanPrompt);
    }

    if (intent == UserIntent.liveWebWorld || intent == UserIntent.hybrid) {
      webResult = await _webSearchTool.search(cleanPrompt);
    }

    final localMemoriesCount =
        (personalResult?.memories.length ?? 0) + (personalResult?.edges.length ?? 0);
    final webResultsCount = webResult?.items.length ?? 0;

    // 3. Check BYOK & Offline status
    final isOfflineOnly = await _byokManager.isOfflineOnly();
    final provider = await _byokManager.getSelectedProvider();
    final hasKey = await _byokManager.hasActiveKey();

    // If offline mode is toggled, or no cloud API key is configured,
    // or provider is explicitly offline local -> run local deterministic engine
    if (isOfflineOnly || !hasKey || provider == AiProvider.offlineLocal) {
      final localText = _generateDeterministicLocalResponse(
        cleanPrompt,
        intent,
        personalResult,
        webResult,
        isAirGapped: isOfflineOnly,
      );

      return RagResponse(
        text: localText,
        tokensMasked: 0,
        localMemoriesUsed: localMemoriesCount,
        webResultsUsed: webResultsCount,
        intent: intent,
        isOfflineEngine: true,
        providerUsed: isOfflineOnly ? 'Air-Gapped Local Engine' : 'Local Deterministic Core',
      );
    }

    // 4. Cloud LLM with On-Device PII Masking
    try {
      return await _dispatchCloudQueryWithMasking(
        prompt: cleanPrompt,
        intent: intent,
        personalResult: personalResult,
        webResult: webResult,
        provider: provider,
      );
    } catch (e) {
      debugPrint('[HybridRagOrchestrator] Cloud LLM error: $e. Falling back to local engine.');
      final fallbackText = _generateDeterministicLocalResponse(
        cleanPrompt,
        intent,
        personalResult,
        webResult,
        isAirGapped: false,
        errorNote: 'Notice: Cloud provider request failed ($e). Operating via Local Engine.',
      );

      return RagResponse(
        text: fallbackText,
        tokensMasked: 0,
        localMemoriesUsed: localMemoriesCount,
        webResultsUsed: webResultsCount,
        intent: intent,
        isOfflineEngine: true,
        providerUsed: 'Local Fallback Core',
      );
    }
  }

  /// Masks PII, dispatches cloud API request, and restores PII upon receiving response.
  Future<RagResponse> _dispatchCloudQueryWithMasking({
    required String prompt,
    required UserIntent intent,
    required KnowledgeQueryResult? personalResult,
    required WebSearchResult? webResult,
    required AiProvider provider,
  }) async {
    // Format personal context
    final personalContextRaw = _formatPersonalContextRaw(personalResult);

    // Apply zero-leakage PII Masking to personal context and user prompt
    final maskedContext = _piiMaskingService.mask(personalContextRaw);
    final maskedPrompt = _piiMaskingService.mask(prompt);

    // Merge token maps
    final mergedTokenMap = <String, String>{
      ...maskedContext.tokenMap,
      ...maskedPrompt.tokenMap,
    };

    final webContextText = webResult?.formatForContext() ?? '';

    // Invoke Cloud LLM
    String cloudReply;
    if (provider == AiProvider.gemini) {
      final geminiKey = await _byokManager.getGeminiApiKey();
      cloudReply = await _invokeGemini(
        apiKey: geminiKey ?? '',
        maskedPrompt: maskedPrompt.maskedText,
        maskedContext: maskedContext.maskedText,
        webContext: webContextText,
      );
    } else {
      final openAiKey = await _byokManager.getOpenAiApiKey();
      final baseUrl = await _byokManager.getOpenAiBaseUrl();
      cloudReply = await _invokeOpenAiCompatible(
        apiKey: openAiKey ?? '',
        baseUrl: baseUrl,
        maskedPrompt: maskedPrompt.maskedText,
        maskedContext: maskedContext.maskedText,
        webContext: webContextText,
      );
    }

    // Restore PII tokens locally on device
    final restoredResponse = _piiMaskingService.unmask(cloudReply, mergedTokenMap);

    return RagResponse(
      text: restoredResponse,
      tokensMasked: mergedTokenMap.length,
      localMemoriesUsed:
          (personalResult?.memories.length ?? 0) + (personalResult?.edges.length ?? 0),
      webResultsUsed: webResult?.items.length ?? 0,
      intent: intent,
      isOfflineEngine: false,
      providerUsed: provider.displayName,
    );
  }

  /// Direct REST invocation of Google Gemini Free-tier API
  Future<String> _invokeGemini({
    required String apiKey,
    required String maskedPrompt,
    required String maskedContext,
    required String webContext,
  }) async {
    final uri = Uri.parse(
      'https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=$apiKey',
    );

    final systemInstruction =
        'You are Matrix AI OS, a privacy-first on-device personal operating system. '
        'Personal identifiers in the context appear as privacy tokens like [PHONE_1], [ACCOUNT_1], [ID_DOC_1]. '
        'You MUST preserve these exact privacy tokens in your response so the user device can restore them locally. '
        'Answer concisely and accurately based on the provided context.';

    final userContent = StringBuffer();
    if (maskedContext.isNotEmpty) {
      userContent.writeln('=== LOCAL ENCRYPTED CONTEXT (ANONYMIZED) ===');
      userContent.writeln(maskedContext);
      userContent.writeln();
    }
    if (webContext.isNotEmpty) {
      userContent.writeln(webContext);
      userContent.writeln();
    }
    userContent.writeln('USER QUERY: $maskedPrompt');

    final body = jsonEncode({
      'contents': [
        {
          'parts': [
            {'text': '$systemInstruction\n\n${userContent.toString()}'}
          ]
        }
      ],
      'generationConfig': {
        'temperature': 0.2,
        'maxOutputTokens': 1024,
      }
    });

    final res = await _client.post(
      uri,
      headers: {'Content-Type': 'application/json'},
      body: body,
    ).timeout(const Duration(seconds: 15));

    if (res.statusCode == 200) {
      final json = jsonDecode(res.body) as Map<String, dynamic>;
      final candidates = json['candidates'] as List<dynamic>?;
      if (candidates != null && candidates.isNotEmpty) {
        final content = candidates[0]['content'] as Map<String, dynamic>?;
        final parts = content?['parts'] as List<dynamic>?;
        if (parts != null && parts.isNotEmpty) {
          return (parts[0]['text'] as String? ?? '').trim();
        }
      }
      return 'No response generated by Gemini model.';
    } else {
      throw Exception('Gemini API returned HTTP ${res.statusCode}: ${res.body}');
    }
  }

  /// Direct REST invocation of OpenAI-compatible API
  Future<String> _invokeOpenAiCompatible({
    required String apiKey,
    required String baseUrl,
    required String maskedPrompt,
    required String maskedContext,
    required String webContext,
  }) async {
    final cleanBase = baseUrl.endsWith('/') ? baseUrl.substring(0, baseUrl.length - 1) : baseUrl;
    final uri = Uri.parse('$cleanBase/chat/completions');

    final systemPrompt =
        'You are Matrix AI OS, a privacy-first on-device personal operating system. '
        'Personal identifiers in the context appear as privacy tokens like [PHONE_1], [ACCOUNT_1], [ID_DOC_1]. '
        'Preserve these exact tokens in your response so the user device can restore them locally.';

    final userContent = StringBuffer();
    if (maskedContext.isNotEmpty) {
      userContent.writeln('=== LOCAL ENCRYPTED CONTEXT (ANONYMIZED) ===');
      userContent.writeln(maskedContext);
      userContent.writeln();
    }
    if (webContext.isNotEmpty) {
      userContent.writeln(webContext);
      userContent.writeln();
    }
    userContent.writeln('USER QUERY: $maskedPrompt');

    final body = jsonEncode({
      'model': 'gpt-4o-mini',
      'messages': [
        {'role': 'system', 'content': systemPrompt},
        {'role': 'user', 'content': userContent.toString()}
      ],
      'temperature': 0.2,
      'max_tokens': 1024,
    });

    final res = await _client.post(
      uri,
      headers: {
        'Content-Type': 'application/json',
        'Authorization': 'Bearer $apiKey',
      },
      body: body,
    ).timeout(const Duration(seconds: 15));

    if (res.statusCode == 200) {
      final json = jsonDecode(res.body) as Map<String, dynamic>;
      final choices = json['choices'] as List<dynamic>?;
      if (choices != null && choices.isNotEmpty) {
        final message = choices[0]['message'] as Map<String, dynamic>?;
        return (message?['content'] as String? ?? '').trim();
      }
      return 'No response generated by model.';
    } else {
      throw Exception('OpenAI API returned HTTP ${res.statusCode}: ${res.body}');
    }
  }

  /// Formats raw personal memories and graph links into context text.
  String _formatPersonalContextRaw(KnowledgeQueryResult? personalResult) {
    if (personalResult == null || personalResult.isEmpty) return '';

    final buffer = StringBuffer();
    if (personalResult.edges.isNotEmpty) {
      buffer.writeln('Personal Knowledge Connections:');
      for (final e in personalResult.edges) {
        buffer.writeln('- (${e.sourceEntity}) --[${e.relationType}]--> (${e.targetEntity}) [${e.context}]');
      }
      buffer.writeln();
    }

    if (personalResult.memories.isNotEmpty) {
      buffer.writeln('Relevant Local Encrypted Records:');
      for (final m in personalResult.memories) {
        buffer.writeln('- [${m.category}] ${m.content}');
      }
    }

    return buffer.toString().trim();
  }

  /// 100% Offline Deterministic Engine providing direct local responses
  /// without requiring internet access or external cloud models.
  String _generateDeterministicLocalResponse(
    String prompt,
    UserIntent intent,
    KnowledgeQueryResult? personalResult,
    WebSearchResult? webResult, {
    required bool isAirGapped,
    String? errorNote,
  }) {
    final buffer = StringBuffer();

    if (errorNote != null) {
      buffer.writeln('> $errorNote\n');
    } else if (isAirGapped) {
      buffer.writeln('> 🛡️ *100% Air-Gapped Mode active. Running entirely on-device.*\n');
    }

    switch (intent) {
      case UserIntent.personalMemory:
        if (personalResult != null && personalResult.isNotEmpty) {
          buffer.writeln('Here is what I found in your personal encrypted memory:\n');
          if (personalResult.memories.isNotEmpty) {
            for (final m in personalResult.memories) {
              buffer.writeln('• **${m.category.toUpperCase()}**: ${m.content}');
            }
          }
          if (personalResult.edges.isNotEmpty) {
            buffer.writeln('\n**Knowledge Graph Connections:**');
            for (final e in personalResult.edges) {
              buffer.writeln('• ${e.sourceEntity} → *${e.relationType}* → ${e.targetEntity} (${e.context})');
            }
          }
        } else {
          buffer.writeln(
            'I checked your encrypted local storage, but found no matching records for "$prompt". '
            'You can trigger log synchronization or index gallery photos from the Core Dashboard.',
          );
        }
        break;

      case UserIntent.liveWebWorld:
        if (webResult != null && webResult.isSuccess) {
          buffer.writeln('Here are live web results for "$prompt":\n');
          for (final item in webResult.items) {
            buffer.writeln('• **${item.title}**');
            buffer.writeln('  ${item.snippet}');
            if (item.url.isNotEmpty) {
              buffer.writeln('  [Source](${item.url})');
            }
            buffer.writeln();
          }
        } else {
          buffer.writeln(
            isAirGapped
                ? 'Air-Gapped Mode is active. Live web search is disabled to preserve complete network isolation.'
                : 'Unable to retrieve live web results at this moment. Please check your network connection or try again.',
          );
        }
        break;

      case UserIntent.hybrid:
        buffer.writeln('**Hybrid Overview:**\n');
        if (personalResult != null && personalResult.isNotEmpty) {
          buffer.writeln('**Personal Data:**');
          for (final m in personalResult.memories.take(3)) {
            buffer.writeln('• [${m.category}] ${m.content}');
          }
          buffer.writeln();
        }
        if (webResult != null && webResult.isSuccess) {
          buffer.writeln('**Live Web Information:**');
          for (final item in webResult.items.take(2)) {
            buffer.writeln('• **${item.title}**: ${item.snippet}');
          }
        }
        break;
    }

    return buffer.toString().trim();
  }
}
